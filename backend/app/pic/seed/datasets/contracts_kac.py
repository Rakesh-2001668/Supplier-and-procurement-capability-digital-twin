"""D12 Contract portfolio of the mock client KAC: ILLUSTRATIVE SAMPLE (fictional contracts, clause wording from the illustrative library, not legal advice).

Tenant KAC (Kaveri Auto Components, pack ``erp_client_kac``) arrives from SAP with its 40 outline agreements. This pack adds what the
client's contract register would add: master agreements with call-off contracts under them, NDAs, rate cards and statements of work
(services, IT, logistics, facilities), 60 contracts in all, from the mock register export ``backend/data/erp_mock/KAC_CLM`` (generated by
``app.pic.tools.erp_mock_contracts``, layout in docs/PIC_ERP_Extract_Spec.md section 10) with the real loader
``app.pic.tools.contract_load``. Clauses are the clause library's (some on its pre-approved fallbacks, a few non-standard and risky),
with obligations and milestones (on time, late, overdue), rebate agreements with tiers, amendment histories, contracts that expire within
30 / 90 / 120 days for the renewals calendar, one in negotiation with supplier redlines, one terminated, and signed contracts.

To use the client's own register instead: put its export in another folder and run ``python -m app.pic.tools.contract_load --tenant KAC --dir <folder>``.
"""
from datetime import date

from app.pic.platform import clock
from app.pic.seed.axion import at

KEY = "contracts-kac"
VERSION = "1"
TITLE = "D12 Contract portfolio of tenant KAC from a mock contract-register export (ILLUSTRATIVE SAMPLE)"
TENANTS = ("KAC",)
CREATES_TENANT = False
READY = True
REQUIRES = {"erp-client-kac": "1"}
LOAD_AT = (date(2026, 11, 1), 8)     # one hour after the SAP cutover load


def data_dir():
    from app.pic.tools.contract_load import DEFAULT_DIR
    return DEFAULT_DIR


def apply(tenant_code: str, password: str) -> dict:
    from app.pic.tools import contract_load

    if tenant_code != TENANTS[0]:
        raise ValueError(f"{KEY} loads tenant {TENANTS[0]} only")
    summary = contract_load.load(tenant_code, data_dir(), when=at(*LOAD_AT))
    clock.set_pinned(None)
    status = summary["byStatus"]
    notes = [
        f"Loaded {summary['loaded']} contracts for {tenant_code} from the mock register export {summary['extractId']} (ILLUSTRATIVE SAMPLE): "
        + ", ".join(f"{n} {t.replace('_', ' ').lower()}" for t, n in sorted(summary["byType"].items())),
        "By status: " + ", ".join(f"{n} {s.lower()}" for s, n in sorted(status.items())),
        f"Clauses by position: {summary['clauses']}; obligations by status: {summary['obligations']}; {summary['rebates']} rebate agreement(s), "
        f"{summary['amendments']} amendment(s), {summary['signatures']} signature record(s), {summary['redlinesPending']} supplier redline(s) pending review",
        f"Rejected {len(summary['rejects'])} row(s)" + ("" if not summary["rejects"] else ": " + "; ".join(f"{r['key']} {r['reason']}" for r in summary["rejects"][:5])),
    ]
    return {"notes": notes, "counts": {"contracts": summary["loaded"], **{f"type:{k}": v for k, v in summary["byType"].items()},
                                       **{f"status:{k}": v for k, v in status.items()}, "rebates": summary["rebates"], "amendments": summary["amendments"]},
            "load": {k: v for k, v in summary.items() if k != "rejects"}, "rejects": len(summary["rejects"])}
