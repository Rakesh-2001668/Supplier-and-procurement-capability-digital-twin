def data_dir():
    from app.pic.tools.erp_mock import OUT_DIR
    return OUT_DIR


def organisation(directory=None) -> dict:
    """Company code, plants and cost objects of the extract (T001, T001W, CSKS, PRPS) for the tenant bootstrap."""
    directory = directory or data_dir()

    def rows(name):
        with open(directory / f"{name}.csv", encoding="utf-8-sig", newline="") as f:
            return list(csv.DictReader(f))

    company = rows("T001")[0]
    plants = [(r["WERKS"], f"{r['NAME1']} - {r['ORT01']}", r["GSTIN"][:2]) for r in rows("T001W") if r["BUKRS"] == company["BUKRS"]]
    cost_objects = [("COST_CENTER", r["KOSTL"], r["LTEXT"] or r["KTEXT"]) for r in rows("CSKS") if r["BUKRS"] == company["BUKRS"]]
    cost_objects += [("WBS", r["POSID"], r["POST1"]) for r in rows("PRPS") if r["PBUKR"] == company["BUKRS"]]
    return {"company": (company["BUKRS"], company["BUTXT"], company["GSTIN"]), "name": company["BUTXT"], "plants": plants,
            "cost_objects": cost_objects}


def apply(tenant_code: str, password: str) -> dict:
    from app.pic.tools import erp_load

    if tenant_code != TENANTS[0]:
        raise ValueError(f"{KEY} creates tenant {TENANTS[0]} only")
    org = organisation()
    clock.set_pinned(at(LOAD_AT[0], 6))
    sc = kit.setup_tenant(tenant_code, org["name"], "MANUFACTURING", company=org["company"], plants=org["plants"], cost_objects=org["cost_objects"],
                          holidays=[], domain=DOMAIN, role_user=ROLE_USER)
    users = kit.create_users(sc, USERS, password)
    summary = erp_load.load(tenant_code, data_dir(), when=at(*LOAD_AT))
    clock.set_pinned(None)
    objects = summary["objects"]
    spend = summary["tieOut"]["spend"]
    notes = [
        f"Tenant {tenant_code} ({org['name']}, fictional) bootstrapped from the extract: company code {org['company'][0]}, plants "
        f"{', '.join(p[0] for p in org['plants'])}, {len(org['cost_objects'])} cost objects; {users} users",
        "Loaded: " + ", ".join(f"{k} {v['loaded']}" for k, v in objects.items() if v.get("loaded")),
        f"Rejected {summary['rejects']['count']} row(s): " + "; ".join(f"{obj} " + ", ".join(f"{r} {n}" for r, n in reasons.items())
                                                                      for obj, reasons in summary["rejects"]["byReason"].items()),
        f"Spend tie-out vs GL (±{spend['tolerancePct']} %): {spend['byStatus']}; exceptions "
        + ", ".join(f"{e['period']} {e['status']}" for e in spend["exceptions"]),
        f"Open AP: loaded + rejected = GL vendor account: {summary['tieOut']['openAp']['loadedPlusRejectedMatchesGl']}; "
        f"open PO value differences explained by rejects: {all(d['explainedByRejects'] for d in summary['tieOut']['openPo']['differences'])}",
        f"Duration {summary['durationSeconds']} s",
    ]
    return {"notes": notes, "counts": {k: v.get("loaded", 0) for k, v in objects.items()}, "load": summary}
