"""D18 ERP client delta migration demo: live inbound delta sync on tenant KAC (TD §12.1 and §12.4).

Executes post-cutover Day-1 ERP delta sync across all 8 kinds on tenant KAC from
the mock extract in backend/data/erp_mock/KAC_DELTA (generated by app.pic.tools.erp_delta_mock).
"""
import shutil
import tempfile
from datetime import date
from pathlib import Path

from app.pic.services import erp_sync
from app.pic.tools import erp_delta_mock

KEY = "erp-delta-kac"
VERSION = "1"
TITLE = "D18 ERP client delta sync: tenant KAC post-cutover inbound sync from mock S/4HANA delta (TD §12.1)"
TENANTS = ("KAC",)
CREATES_TENANT = False
READY = True
REQUIRES = {"erp-client-kac": "1"}
SYNC_AT = (date(2026, 11, 2), 18)     # Day-1 post-cutover evening run


def apply(tenant_code: str, password: str) -> dict:
    if tenant_code != TENANTS[0]:
        raise ValueError(f"{KEY} loads tenant {TENANTS[0]} only")

    temp_dir = Path(tempfile.mkdtemp(prefix="pic-kac-delta-"))
    try:
        erp_delta_mock.stage_drop(temp_dir)
        results = {}
        for kind in ("PLANTS", "COST_OBJECTS", "VENDORS", "MATERIALS", "STOCK", "OPEN_POS", "PAYMENT_STATUS", "PLANNED_ORDERS"):
            results[kind] = erp_sync.run(tenant_code, kind, directory=temp_dir, mode="SCHEDULED", source="FILE_DROP")

        notes = [
            f"Executed live inbound ERP delta sync across 8 kinds for {tenant_code} from {erp_delta_mock.EXTRACT_ID}:",
            f"  Vendors: {results['VENDORS']['counts']}, status: {results['VENDORS']['status']}",
            f"  Materials: {results['MATERIALS']['counts']}, status: {results['MATERIALS']['status']}",
            f"  Stock: {results['STOCK']['counts']}, status: {results['STOCK']['status']}",
            f"  Open POs: {results['OPEN_POS']['counts']}, status: {results['OPEN_POS']['status']}",
            f"  Payment Status: {results['PAYMENT_STATUS']['counts']}, status: {results['PAYMENT_STATUS']['status']}",
        ]
        return {
            "notes": notes,
            "counts": {f"{k.lower()}:{v['status']}": 1 for k, v in results.items()},
        }
    finally:
        shutil.rmtree(temp_dir, ignore_errors=True)

